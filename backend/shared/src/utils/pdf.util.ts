import PDFDocument from 'pdfkit';

export interface PdfColumn<T = any> {
  header: string;
  accessor: (item: T) => string | number | boolean | null | undefined;
  width?: number;
}

export const generatePdfReport = <T = any>(
  title: string,
  columns: PdfColumn<T>[],
  data: T[]
): Promise<Buffer> => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: 'A4',
        margin: 35,
        bufferPages: true,
      });

      const buffers: Buffer[] = [];
      doc.on('data', (chunk) => buffers.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(buffers)));
      doc.on('error', (err) => reject(err));

      // Page dimensions
      const pageWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;
      const startX = doc.page.margins.left;
      let startY = doc.page.margins.top;

      // 1. Header Section
      doc.fillColor('#1E293B').fontSize(18).font('Helvetica-Bold').text('Inventory Management System', startX, startY);
      startY += 24;

      doc.fillColor('#475569').fontSize(12).font('Helvetica-Bold').text(title, startX, startY);
      startY += 16;

      const generatedAt = new Date().toUTCString();
      doc.fillColor('#64748B').fontSize(9).font('Helvetica').text(`Generated Date: ${generatedAt}`, startX, startY);
      startY += 20;

      // Horizontal Divider
      doc.moveTo(startX, startY).lineTo(startX + pageWidth, startY).strokeColor('#E2E8F0').lineWidth(1).stroke();
      startY += 15;

      // Calculate Column Widths
      const totalCustomWidth = columns.reduce((acc, col) => acc + (col.width || 0), 0);
      const unassignedCols = columns.filter((col) => !col.width).length;
      const remainingWidth = Math.max(pageWidth - totalCustomWidth, 0);
      const defaultWidth = unassignedCols > 0 ? remainingWidth / unassignedCols : 100;

      const colWidths = columns.map((col) => col.width || defaultWidth);

      // 2. Draw Table Header
      const headerHeight = 22;
      doc.rect(startX, startY, pageWidth, headerHeight).fill('#4F46E5');

      let currentX = startX;
      columns.forEach((col, idx) => {
        const w = colWidths[idx];
        doc
          .fillColor('#FFFFFF')
          .fontSize(9)
          .font('Helvetica-Bold')
          .text(col.header, currentX + 5, startY + 6, {
            width: w - 10,
            align: 'left',
            ellipsis: true,
          });
        currentX += w;
      });

      startY += headerHeight;

      // 3. Draw Data Rows
      const rowHeight = 20;
      const maxY = doc.page.height - doc.page.margins.bottom - 40;

      data.forEach((item, rowIndex) => {
        // Check if page break is needed
        if (startY + rowHeight > maxY) {
          doc.addPage();
          startY = doc.page.margins.top;

          // Re-draw header on new page
          doc.rect(startX, startY, pageWidth, headerHeight).fill('#4F46E5');
          let pageHeaderX = startX;
          columns.forEach((col, idx) => {
            const w = colWidths[idx];
            doc
              .fillColor('#FFFFFF')
              .fontSize(9)
              .font('Helvetica-Bold')
              .text(col.header, pageHeaderX + 5, startY + 6, {
                width: w - 10,
                align: 'left',
                ellipsis: true,
              });
            pageHeaderX += w;
          });
          startY += headerHeight;
        }

        // Alternating row background
        if (rowIndex % 2 === 0) {
          doc.rect(startX, startY, pageWidth, rowHeight).fill('#F8FAFC');
        } else {
          doc.rect(startX, startY, pageWidth, rowHeight).fill('#FFFFFF');
        }

        let cellX = startX;
        columns.forEach((col, idx) => {
          const w = colWidths[idx];
          const rawVal = col.accessor(item);
          const textVal = rawVal === null || rawVal === undefined ? '—' : String(rawVal);

          doc
            .fillColor('#334155')
            .fontSize(8)
            .font('Helvetica')
            .text(textVal, cellX + 5, startY + 5, {
              width: w - 10,
              align: 'left',
              ellipsis: true,
            });
          cellX += w;
        });

        startY += rowHeight;
      });

      // 4. Add Footers on all buffered pages
      const range = doc.bufferedPageRange();
      for (let i = range.start; i < range.start + range.count; i++) {
        doc.switchToPage(i);
        const footerY = doc.page.height - doc.page.margins.bottom + 10;

        doc.moveTo(startX, footerY - 5).lineTo(startX + pageWidth, footerY - 5).strokeColor('#E2E8F0').lineWidth(0.5).stroke();

        doc
          .fillColor('#94A3B8')
          .fontSize(8)
          .font('Helvetica')
          .text('Generated by Inventory Management System', startX, footerY, {
            width: pageWidth / 2,
            align: 'left',
          });

        doc
          .fillColor('#94A3B8')
          .fontSize(8)
          .font('Helvetica')
          .text(`Page ${i + 1} of ${range.count}`, startX + pageWidth / 2, footerY, {
            width: pageWidth / 2,
            align: 'right',
          });
      }

      doc.end();
    } catch (error) {
      reject(error);
    }
  });
};
